#!/usr/bin/env bash
# Prepare the repo for GitHub: remove junk, resolve the _v2/_v3 files into
# clean names, fix internal references, write .gitignore, and git init.
#
# DESTRUCTIVE. It deletes superseded files. Read it before running.
# It stops before committing so you can review what is staged.
#
# Run from the repo root:  bash prep_repo.sh

set -uo pipefail
cd "$(dirname "$0")"

echo "=============== 1. junk ==============="
rm -f .DS_Store .Rhistory
# bcftools wrote these to the cwd when it read the remote VCFs
rm -f 20201028_CCDG_14151_B01_GRM_WGS_*.recalibrated_variants.vcf.gz.tbi
echo "  removed .DS_Store, .Rhistory, and stray remote .tbi indexes"

echo
echo "=============== 2. resolve versioned files ==============="
# Each of these went through revisions during the work. The reasoning is
# recorded in docs/, so the intermediate files do not need to survive.
mv -f README_v2.md README.md

mv -f docs/calibration_result_v2.md docs/calibration_result.md
mv -f docs/panel_notes_v2.md        docs/panel_notes.md
mv -f docs/power_result_v2.md       docs/power_result.md
mv -f docs/rare_qc_result_v2.md     docs/rare_qc_result.md

mv -f scripts/02_fetch_refs_v2.sh scripts/02_fetch_refs.sh
rm -f scripts/10_run_full.sh scripts/10_run_full_v2.sh
mv -f scripts/10_run_full_v3.sh scripts/10_run_full.sh
rm -f scripts/11_analyze.py scripts/11_analyze_v2.py
mv -f scripts/11_analyze_v3.py scripts/11_analyze.py
rm -f scripts/12_sim_power.py scripts/12_sim_power_v2.py
mv -f scripts/12_sim_power_v3.py scripts/12_sim_power.py

rm -f nextflow/main.nf nextflow/main_v2.nf nextflow/main_v3.nf
mv -f nextflow/main_v4.nf nextflow/main.nf

# The heterozygote-excess QC was abandoned before producing any used result.
# docs/rare_qc_result.md explains why. The scripts and its output go.
rm -f scripts/04b_qc_summary.py scripts/04b_qc_summary_v2.py results/gene_qc.tsv

# Superseded by panel_genes_17q21.txt; the file is already a deprecation stub.
rm -f config/control_genes.txt
echo "  done"

echo
echo "=============== 3. fix internal references ==============="
sed -i '' 's|12_sim_power_v[23]\.py|12_sim_power.py|g' \
    scripts/12_run_power_pilot2.sh scripts/12_run_power_pilot3.sh \
    scripts/14_run_power_full.sh 2>/dev/null
sed -i '' 's|11_analyze_v3\.py|11_analyze.py|g' nextflow/main.nf 2>/dev/null
sed -i '' 's|main_v[234]\.nf|main.nf|g' scripts/15_setup_nextflow.sh 2>/dev/null
sed -i '' 's|13_power_analyze\.py|13_power_analyze.py|g' scripts/12_run_power_pilot.sh 2>/dev/null

echo "  remaining references to versioned filenames (should be none):"
grep -rn "_v[234]\.\(py\|sh\|nf\|md\)" scripts/ nextflow/ docs/ README.md 2>/dev/null \
  | grep -v "^docs/" | sed 's/^/    /' || echo "    none"

echo
echo "=============== 4. .gitignore ==============="
cat > .gitignore <<'EOF'
# Input and intermediate data. All of it is regenerable from scripts/ and the
# public sources documented in the README. None of it belongs in git.
data/
ref/
results/regenie/
results_nf_smoke/

# Simulated phenotypes: ~124 MB, regenerated by scripts/09_make_phenos.py
# and scripts/12_sim_power.py from fixed seeds.
config/pheno_*.tsv

# Large derived tables, regenerable from scripts/04, 05 and 07
results/*.tsv.gz

# Nextflow
work/
.nextflow/
.nextflow.log*

# OS and editor
.DS_Store
.Rhistory
.ipynb_checkpoints/
__pycache__/
EOF
echo "  written"

echo
echo "=============== 5. git ==============="
if [ ! -d .git ]; then
  git init -q
  git branch -M main
  echo "  initialized"
else
  echo "  already a git repo"
fi

git add -A

echo
echo "  files staged: $(git diff --cached --name-only | wc -l | tr -d ' ')"
echo "  total staged size:"
git diff --cached --name-only | xargs -I{} du -k "{}" 2>/dev/null \
  | awk '{s+=$1} END {printf "    %.1f MB\n", s/1024}'
echo
echo "  largest staged files:"
git diff --cached --name-only | xargs -I{} du -k "{}" 2>/dev/null \
  | sort -rn | head -8 | awk '{printf "    %7.1f KB  %s\n", $1, $2}'
echo
echo "  by directory:"
git diff --cached --name-only | cut -d/ -f1 | sort | uniq -c \
  | awk '{printf "    %4d  %s\n", $1, $2}'

echo
echo "=============== NOT COMMITTED ==============="
echo "Review with:  git status --short"
echo "Anything above 1 MB that is not config/regenie_annot.tsv or"
echo "config/covariates.tsv is probably a mistake."
